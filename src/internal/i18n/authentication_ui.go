// AuthenticationUI returns a copy of the complete page vocabulary for one supported language.
func AuthenticationUI(lang Language) map[string]string {
	phrases, ok := authenticationPhrases[lang]
	if !ok {
		phrases = authenticationPhrases[LangEN]
	}
	out := make(map[string]string, len(phrases))
	for k, v := range phrases {
		out[k] = v
	}
	return out
}

